"""从答案正文里抽取引用编号。

正文里的 `[1]` 是**唯一**能把「模型说的这句话」和「哪条资料支撑它」连起来的
东西,所以抽取的正确性直接决定引用面板可不可信。它错起来是静默的:

- 抽多了一个 → 用户点开来源卡片看到的是无关资料;
- 抽漏了一个 → 一条真实的引用被显示成「无来源」。

两种都不会抛异常,只会让人慢慢不再相信引用面板。所以这里对越界编号的
处理是**丢弃而不是保留**:保留一个指向不存在卡片的 `[9]`,前端要么渲染出
空卡片、要么点击时崩掉;丢弃只是少标一条,后果轻得多。

**为什么范围过滤比「像年份就排除」更可靠**:`max_index` 把「引用编号不可能
超过资料条数」这条硬约束直接变成过滤条件,顺带解决了 `[2024]`(年份)、
`[12]`(库存)这类误匹配,而不需要维护一张启发式规则表。
"""

from __future__ import annotations

import re

# 半角 `[]` 与全角 `【】` 都认。
#
# **全角不是可有可无的兼容**:提示词里写的是半角 `[1]`,但中文模型把中括号
# 写成 `【1】` 是高频现象。只认半角的话这类答案会被判成「完全没有引用」,
# 而答案读起来完全正常,只是来源卡片全是灰的——一个没人会去查的缺陷。
#
# 一个方括号里允许逗号/顿号分隔多个编号(`[1,2]`、`[1、3]`),这是模型
# 合并引用时的常见写法。
_CITATION_RE = re.compile(r"[\[【]\s*(\d+(?:\s*[,、]\s*\d+)*)\s*[\]】]")

_SPLIT_RE = re.compile(r"[,、]")


def extract_citations(text: str, *, max_index: int) -> list[int]:
    """返回正文里被引用的资料编号,**去重、升序、去掉越界**。编号从 1 起。

    `max_index` 是本次上下文里实际装进去的资料条数(即 `len(bundle.used)`)。
    传 0 表示上下文为空,此时任何编号都越界,结果恒为空列表。
    """
    if not text or max_index <= 0:
        return []

    found: set[int] = set()
    for group in _CITATION_RE.findall(text):
        for raw in _SPLIT_RE.split(group):
            raw = raw.strip()
            if not raw:
                continue
            number = int(raw)
            # `[0]` 与 `[2024]` 都在这里被挡掉。上限用 max_index 而不是
            # 某个魔法数字,是因为它就是「资料条数」这个事实本身。
            if 1 <= number <= max_index:
                found.add(number)

    return sorted(found)
